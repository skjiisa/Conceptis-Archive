#!/usr/bin/env python3
"""Generate the archive's Markdown from its folder contents.

Layout this expects:

    <App>/<YYYY-MM-DD>/info.png
    <App>/<YYYY-MM-DD>/puzzle.png
    <App>/<YYYY-MM-DD>/complete.png

Any top-level folder that contains at least one date-named folder is treated
as an app. The script writes:

    <App>/<date>/README.md   a table of that week's images, with prev/next links
    <App>/README.md          a thumbnail grid of every week, newest first
    README.md                the section between the archive markers

Every file it writes is fully regenerated, so don't edit them by hand. Put
notes for a week in <App>/<date>/notes.md and they are included in its page.

Usage:
    python3 scripts/build.py            write files
    python3 scripts/build.py --check    exit 1 if any file is out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp"}
# Known screenshots, in the order they're taken while playing.
KNOWN_IMAGES = ["info", "puzzle", "complete"]
# Which image to use as the thumbnail on the app index, in order of preference.
THUMBNAIL_PREFERENCE = ["complete", "info", "puzzle"]
THUMBNAIL_WIDTH = 160
GRID_COLUMNS = 5
GENERATED_NOTE = "<!-- Generated by scripts/build.py. Do not edit by hand. -->"
ROOT_START = "<!-- archive:start -->"
ROOT_END = "<!-- archive:end -->"


def images_in(week: Path) -> list[Path]:
    """Images in a week folder: known names in play order, then anything else."""
    found = {p.stem.lower(): p for p in week.iterdir()
             if p.is_file() and p.suffix.lower() in IMAGE_EXTS}
    ordered = [found.pop(name) for name in KNOWN_IMAGES if name in found]
    return ordered + sorted(found.values(), key=lambda p: p.name)


def find_apps() -> dict[str, list[Path]]:
    apps = {}
    for d in sorted(ROOT.iterdir()):
        if not d.is_dir() or d.name.startswith("."):
            continue
        weeks = sorted(w for w in d.iterdir() if w.is_dir() and DATE_RE.match(w.name))
        if weeks:
            apps[d.name] = weeks
    return apps


def label(image: Path) -> str:
    return image.stem.replace("-", " ").replace("_", " ").title()


def week_page(app: str, weeks: list[Path], i: int) -> str:
    week = weeks[i]
    images = images_in(week)
    nav = [f"[{app}](../)"]
    if i > 0:
        nav.insert(0, f"[← {weeks[i - 1].name}](../{weeks[i - 1].name}/)")
    if i < len(weeks) - 1:
        nav.append(f"[{weeks[i + 1].name} →](../{weeks[i + 1].name}/)")

    lines = [GENERATED_NOTE, "", f"# {app}: {week.name}", "", " · ".join(nav), ""]
    if images:
        lines.append("| " + " | ".join(label(p) for p in images) + " |")
        lines.append("|" + "|".join(" --- " for _ in images) + "|")
        lines.append("| " + " | ".join(f"![{label(p)}]({p.name})" for p in images) + " |")
    else:
        lines.append("_No images yet._")

    notes = week / "notes.md"
    if notes.is_file():
        lines += ["", notes.read_text(encoding="utf-8").strip()]
    return "\n".join(lines) + "\n"


def thumbnail(week: Path) -> Path | None:
    images = {p.stem.lower(): p for p in images_in(week)}
    for name in THUMBNAIL_PREFERENCE:
        if name in images:
            return images[name]
    return next(iter(images.values()), None)


def app_page(app: str, weeks: list[Path]) -> str:
    lines = [GENERATED_NOTE, "", f"# {app}", "",
             f"{len(weeks)} weeks archived. [Back to the archive](../)", ""]
    newest_first = list(reversed(weeks))
    for year in sorted({w.name[:4] for w in weeks}, reverse=True):
        year_weeks = [w for w in newest_first if w.name.startswith(year)]
        lines += [f"## {year}", "", "<table>"]
        for row_start in range(0, len(year_weeks), GRID_COLUMNS):
            lines.append("<tr>")
            for w in year_weeks[row_start:row_start + GRID_COLUMNS]:
                thumb = thumbnail(w)
                img = (f'<img src="{w.name}/{thumb.name}" width="{THUMBNAIL_WIDTH}" '
                       f'alt="{app} {w.name}"><br>' if thumb else "")
                lines.append(f'<td align="center"><a href="{w.name}/">{img}{w.name}</a></td>')
            lines.append("</tr>")
        lines += ["</table>", ""]
    return "\n".join(lines).rstrip() + "\n"


def root_section(apps: dict[str, list[Path]]) -> str:
    lines = [ROOT_START, GENERATED_NOTE, "", "| App | Weeks | Latest |", "| --- | --- | --- |"]
    for app, weeks in apps.items():
        latest = weeks[-1].name
        lines.append(f"| [{app}]({app}/) | {len(weeks)} | [{latest}]({app}/{latest}/) |")
    lines.append(ROOT_END)
    return "\n".join(lines)


def root_readme(apps: dict[str, list[Path]]) -> str:
    path = ROOT / "README.md"
    text = path.read_text(encoding="utf-8") if path.exists() else "# Conceptis Archive\n"
    section = root_section(apps)
    pattern = re.compile(re.escape(ROOT_START) + r".*?" + re.escape(ROOT_END), re.S)
    if pattern.search(text):
        return pattern.sub(lambda _: section, text)
    return text.rstrip() + "\n\n## Archive\n\n" + section + "\n"


def outputs() -> dict[Path, str]:
    apps = find_apps()
    files = {ROOT / "README.md": root_readme(apps)}
    for app, weeks in apps.items():
        files[ROOT / app / "README.md"] = app_page(app, weeks)
        for i, week in enumerate(weeks):
            files[week / "README.md"] = week_page(app, weeks, i)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="don't write; exit 1 if any generated file is out of date")
    args = parser.parse_args()

    stale = []
    for path, content in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.write_text(content, encoding="utf-8")

    for p in stale:
        print(("out of date: " if args.check else "wrote: ") + str(p))
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
